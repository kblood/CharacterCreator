// Makes an instrumented copy of three-simplecloth (MIT, bandinopla) in simplecloth/patched/ (git-ignored):
// the only change is that the returned API also exposes the particle storage buffer (`positions`, vec4 per
// unique vertex: xyz world position, w = mask) so the experiment can read positions back for the metrics.
// Run after `npm install` in this folder: node patch.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(HERE, 'node_modules/three-simplecloth/dist/index.js');
let js = fs.readFileSync(src, 'utf8');
const needle = 'stiffnessUniform: U,';
if (!js.includes(needle)) throw new Error('three-simplecloth layout changed: patch point not found (tested with 0.0.6)');
js = js.replace(needle, 'positions: h, uniqueCount: l, springCount: y, colliderCount: d.length, ' + needle);
fs.mkdirSync(path.join(HERE, 'patched'), { recursive: true });
fs.writeFileSync(path.join(HERE, 'patched/index.js'),
  '// Instrumented copy of three-simplecloth 0.0.6 dist/index.js (MIT, Copyright 2026 bandinopla). Generated by patch.mjs.\n' + js);
console.log('wrote patched/index.js');
